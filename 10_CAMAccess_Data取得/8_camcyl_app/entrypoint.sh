#!/bin/bash
set -e

echo "======================================================"
echo "CAM/CYL アプリケーションを起動しています..."
echo "起動時刻: $(date '+%Y-%m-%d %H:%M:%S')"
echo "======================================================"
echo ""

# 起動時に1回実行
echo "[起動時処理] データ抽出処理を実行します..."
